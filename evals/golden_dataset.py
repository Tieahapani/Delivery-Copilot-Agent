from datetime import datetime, timedelta


def _sla(minutes_from_now: int) -> str:
    """Helper: SLA deadline N minutes from now."""
    return (datetime.now() + timedelta(minutes=minutes_from_now)).isoformat()


def _eta(minutes_from_now: int) -> str:
    """Helper: ETA N minutes from now."""
    return (datetime.now() + timedelta(minutes=minutes_from_now)).isoformat()


